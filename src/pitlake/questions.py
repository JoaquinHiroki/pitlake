import hashlib
import re
from collections import Counter
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from datetime import date, datetime
from decimal import Decimal

from pitlake.documents import company, long_date
from pitlake.gold import ANNUAL, INSTANT, QUARTER

TRAIN = "train"
VALIDATION = "validation"
TEST = "test"
SPLITS = (TRAIN, VALIDATION, TEST)

LABELS = {
    "revenue": "total net sales",
    "gross_profit": "gross margin",
    "operating_income": "operating income",
    "net_income": "net income",
    "eps_diluted": "diluted earnings per share",
    "operating_cash_flow": "cash generated by operating activities",
    "assets": "total assets",
    "liabilities": "total liabilities",
    "equity": "total shareholders' equity",
    "cash": "cash and cash equivalents",
    "shares_outstanding": "shares of common stock outstanding",
}
PERIODS = {QUARTER: "three months ended {date}", ANNUAL: "fiscal year ended {date}"}
TEMPLATES = {
    (TRAIN, False): (
        "What was {company}'s {label} for the {period}?",
        "{company} {label} for the {period}",
        "How much {label} did {company} report for the {period}?",
    ),
    (TRAIN, True): (
        "What were {company}'s {label} as of {date}?",
        "{company} {label} at {date}",
    ),
    (VALIDATION, False): (
        "Give {company}'s {label} for the {period}.",
        "For the {period}, how much {label} did {company} have?",
    ),
    (VALIDATION, True): ("What did {company} report as {label} on {date}?",),
    (TEST, False): (
        "Report {company}'s {label} in the {period}.",
        "In the {period}, what {label} did {company} record?",
    ),
    (TEST, True): ("As of {date}, how much {label} did {company} have?",),
}
_MILLION = Decimal(1_000_000)
_THOUSAND = Decimal(1_000)


@dataclass(frozen=True)
class Fact:
    symbol: str
    metric: str
    duration: str
    period_end: date
    value: Decimal
    unit: str
    accession_number: str
    knowable_at: datetime


@dataclass(frozen=True)
class Passage:
    chunk_id: str
    symbol: str
    accession_number: str
    text: str


@dataclass(frozen=True)
class Question:
    question_id: str
    split: str
    symbol: str
    metric: str
    duration: str
    period_end: date
    value: Decimal
    accession_number: str
    as_of: datetime
    text: str
    answers: tuple[str, ...]
    relevant: tuple[str, ...]


def split_of(at: datetime, train_until: datetime, test_from: datetime) -> str:
    if at < train_until:
        return TRAIN
    if at < test_from:
        return VALIDATION
    return TEST


def answer_strings(value: Decimal, unit: str) -> tuple[str, ...]:
    magnitude = abs(Decimal(value))
    if unit == "USD/shares":
        return (f"{magnitude:.2f}",)
    found = [f"{magnitude:,.0f}"] if unit == "shares" else []
    for scale in (_MILLION, _THOUSAND):
        if magnitude >= _MILLION and magnitude % scale == 0:
            found.append(f"{magnitude / scale:,.0f}")
    return tuple(dict.fromkeys(found))


def answer_pattern(answers: Sequence[str]) -> re.Pattern:
    if not answers:
        raise ValueError("no answer strings")
    either = "|".join(re.escape(a) for a in answers)
    return re.compile(rf"(?<![\d.,])(?:{either})(?![\d]|[.,]\d)")


def first_reports(facts: Iterable[Fact]) -> list[Fact]:
    first: dict[tuple, Fact] = {}
    for fact in facts:
        key = (fact.symbol, fact.metric, fact.duration, fact.period_end)
        held = first.get(key)
        if held is None or (fact.knowable_at, fact.accession_number) < (
            held.knowable_at,
            held.accession_number,
        ):
            first[key] = fact
    return sorted(first.values(), key=lambda f: (f.knowable_at, f.symbol, f.metric, f.duration))


def _choose(options: Sequence[str], key: str) -> str:
    return options[int(hashlib.sha256(key.encode()).hexdigest(), 16) % len(options)]


def phrase(fact: Fact, split: str) -> str:
    instant = fact.duration == INSTANT
    options = TEMPLATES[(split, instant)]
    key = f"{fact.symbol}|{fact.metric}|{fact.duration}|{fact.period_end}"
    when = long_date(fact.period_end)
    return _choose(options, key).format(
        company=company(fact.symbol),
        label=LABELS[fact.metric],
        date=when,
        period="" if instant else PERIODS[fact.duration].format(date=when),
    )


def question_id(fact: Fact, text: str) -> str:
    raw = "|".join(
        [fact.symbol, fact.metric, fact.duration, str(fact.period_end), fact.accession_number, text]
    )
    return hashlib.sha256(raw.encode()).hexdigest()[:32]


def build_questions(
    facts: Iterable[Fact],
    passages: Iterable[Passage],
    train_until: datetime,
    test_from: datetime,
) -> tuple[list[Question], Counter]:
    if test_from < train_until:
        raise ValueError("the test split must start after training ends")
    by_filing: Mapping[tuple[str, str], list[Passage]] = {}
    for passage in passages:
        by_filing.setdefault((passage.symbol, passage.accession_number), []).append(passage)

    questions, dropped = [], Counter()
    for fact in first_reports(f for f in facts if f.metric in LABELS):
        filing = by_filing.get((fact.symbol, fact.accession_number))
        if not filing:
            dropped["no_document"] += 1
            continue
        answers = answer_strings(fact.value, fact.unit)
        if not answers:
            dropped["no_answer_string"] += 1
            continue
        pattern = answer_pattern(answers)
        relevant = tuple(sorted(p.chunk_id for p in filing if pattern.search(p.text)))
        if not relevant:
            dropped[f"value_not_in_text:{fact.metric}"] += 1
            continue
        split = split_of(fact.knowable_at, train_until, test_from)
        text = phrase(fact, split)
        questions.append(
            Question(
                question_id(fact, text),
                split,
                fact.symbol,
                fact.metric,
                fact.duration,
                fact.period_end,
                fact.value,
                fact.accession_number,
                fact.knowable_at,
                text,
                answers,
                relevant,
            )
        )
    return questions, dropped
